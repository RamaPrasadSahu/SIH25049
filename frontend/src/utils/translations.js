// Fallback lookup helper function
export const getTranslation = (langCode, key) => {
  const langDict = TRANSLATIONS[langCode] || TRANSLATIONS['od-IN'] || TRANSLATIONS['en-IN'];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fallback to Odia or English if key is missing in chosen language
  const fallbackDict = TRANSLATIONS['od-IN'] || TRANSLATIONS['en-IN'];
  return (fallbackDict && fallbackDict[key]) || key;
};
