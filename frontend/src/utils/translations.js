// Chat-specific translation keys
const CHAT_KEYS = new Set([
  'chatPlaceholder',
  'recordVoice',
  'stopVoice',
  'sendMessage',
  'disclaimer'
]);

/**
 * Get Translation Helper
 * UI elements (navigation, sidebar, headers, buttons) ALWAYS remain in English for a clean, consistent interface.
 * Only Chat System specific placeholders use the selected target language.
 */
export const getTranslation = (langCode, key) => {
  // If it's a chat system key, use the selected language if available
  if (CHAT_KEYS.has(key)) {
    const chatDict = TRANSLATIONS[langCode] || TRANSLATIONS['en-IN'];
    if (chatDict && chatDict[key]) {
      return chatDict[key];
    }
  }

  // All UI elements stay in clean English
  const englishDict = TRANSLATIONS['en-IN'];
  if (englishDict && englishDict[key]) {
    return englishDict[key];
  }

  return key;
};
